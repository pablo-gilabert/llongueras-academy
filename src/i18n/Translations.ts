function normalizeCourseTitle(value: string): string {
    return value.normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim().toLocaleLowerCase('es');
}
/** Translate known course names, preserving any unknown proper nouns. */
export function localizeCourseName(name: string | null | undefined): string {
    if (!name || ActiveLocale === 'es') return name ?? '';
    const exact = CourseTitleTranslations[normalizeCourseTitle(name)];
    if (exact) return exact[ActiveLocale];
    // Translate domain vocabulary in additional course names without altering the source.
    const tokens = name.match(/\p{L}+|[^\p{L}]+/gu) ?? [];
    return tokens.map(token => {
        const replacement = CourseWordTranslations[normalizeCourseTitle(token)]?.[ActiveLocale];
        if (!replacement) return token;
        return /^\p{Lu}/u.test(token)
            ? replacement.charAt(0).toLocaleUpperCase(ActiveLocale) + replacement.slice(1)
            : replacement;
    }).join('');
}

let ActiveLocale: Locale = 'es';
/** Synchronize the translation helper with the active UI preference. */
export function getActiveLocale(): Locale { return ActiveLocale; }
export function setActiveLocale(locale: Locale): void {
    ActiveLocale = locale;
}
/** Translate display strings while preserving leading and trailing whitespace. */
export function t<Value>(value: Value): Value {
    if (ActiveLocale === 'es' || typeof value !== 'string')
        return value;
    const leading = value.match(/^\s*/)?.[0] ?? '';
    const trailing = value.match(/\s*$/)?.[0] ?? '';
    const trimmed = value.trim();
    if (!trimmed)
        return value;
    const translated = (ActiveLocale === 'pt-BR' ? PortugueseTranslations : EnglishTranslations)[trimmed];
    if (translated)
        return `${leading}${translated}${trailing}` as unknown as Value;
    return (ActiveLocale === 'pt-BR' ? translatePortugueseInterpolated(value) : translateInterpolated(value)) as unknown as Value;
}
/** Translate a small set of interpolated labels rendered by the dashboard. */
function translateInterpolated(value: string): string {
    const patterns: Array<[
        RegExp,
        string
    ]> = [
            [/^(\d+) registros visibles$/, '$1 visible records'],
            [/^Asistencia de (.+)$/, 'Attendance for $1'],
            [/^Nota de (.+)$/, 'Grade for $1'],
            [/^Editar (.+)$/, 'Edit $1'],
            [/^(\d+) registros disponibles para tu perfil$/, '$1 records available for your role'],
            [/^(\d+) alumnos inscriptos$/, '$1 enrolled students'],
            [/^(\d+) alumnos$/, '$1 students'],
            [/^(\d+) resultados$/, '$1 results'],
            [/^(\d+) inscripciones$/, '$1 enrollments'],
            [/^Registrado el (.+)\. El historial de inscripciones se conserva al desactivar un alumno\.$/, 'Registered on $1. Enrollment history is preserved when a student is deactivated.'],
        ];
    for (const [pattern, replacement] of patterns) {
        if (pattern.test(value))
            return value.replace(pattern, replacement);
    }
    return value;
}

/** Translate Portuguese labels containing live record counts. */
function translatePortugueseInterpolated(value: string): string {
    const patterns: Array<[RegExp, string]> = [
        [/^(\d+) registros visibles$/, '$1 registros visíveis'],
        [/^(\d+) alumnos inscriptos$/, '$1 alunos matriculados'],
        [/^(\d+) alumnos$/, '$1 alunos'],
        [/^(\d+) inscripciones$/, '$1 matrículas'],
        [/^(\d+) resultados$/, '$1 resultados'],
        [/^Asistencia de (.+)$/, 'Frequência de $1'],
        [/^Nota de (.+)$/, 'Nota de $1'],
        [/^Editar (.+)$/, 'Editar $1'],
    ];
    for (const [pattern, replacement] of patterns) {
        if (pattern.test(value)) return value.replace(pattern, replacement);
    }
    return value;
}
